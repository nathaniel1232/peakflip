#!/usr/bin/env python3
"""Upload the game's icons and sounds to Roblox and write their ids into the game.

- roblox/assets/icons/*.png  -> Decals -> src/shared/Icons.luau (the server turns each into its image)
- roblox/assets/sounds/*.wav -> Audio  -> src/shared/Sounds.luau (make them with tools/make_sounds.py)

Roblox can only use images and sounds that live on Roblox, so each file is uploaded once to your account.

1. Create an API key at https://create.roblox.com/dashboard/credentials
   - Access permissions: add the "Assets" API system, with Read and Write
   - Accepted IP addresses: 0.0.0.0/0 (or your own IP)
2. Find your user id: it's the number in your profile URL (roblox.com/users/<id>/profile).
3. Run this, then copy the key (Cmd+C) when it asks and press Enter; it reads the key from your
   clipboard (nothing is shown or saved):
     python3 roblox/tools/upload_assets.py
   (ROBLOX_API_KEY / ROBLOX_USER_ID environment variables work too; for a group-owned game set ROBLOX_GROUP_ID)

Files already uploaded are skipped, so it's safe to run again after adding new ones.
Roblox limits how many sounds an account can upload per month; if it says so, run again later.
"""
import json, os, re, subprocess, sys, time, uuid, urllib.request, urllib.error
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KINDS = [
    # folder, extension, asset type, content type, output file, how ids are written
    ("icons", "png", "Decal", "image/png", ROOT / "src" / "shared" / "Icons.luau", "decal:"),
    ("sounds", "wav", "Audio", "audio/wav", ROOT / "src" / "shared" / "Sounds.luau", "rbxassetid://"),
]
API = "https://apis.roblox.com/assets/v1"


def existing(out):
    if not out.exists():
        return {}
    return dict(re.findall(r'(\w+)\s*=\s*"((?:rbxassetid://|decal:)\d+)"', out.read_text()))


def write(out, ids):
    lines = ["-- Generated by tools/upload_assets.py. \"decal:<id>\" entries are turned into images by the server;",
             "-- \"rbxassetid://<id>\" entries are used as they are (you can also paste ids from Studio's Asset Manager).",
             "return {"]
    for name in sorted(ids):
        lines.append(f'\t{name} = "{ids[name]}",')
    lines.append("}")
    out.write_text("\n".join(lines) + "\n")


def request(method, url, key, body=None, headers=None):
    req = urllib.request.Request(url, data=body, method=method, headers={"x-api-key": key, **(headers or {})})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.loads(r.read() or b"{}")
    except urllib.error.HTTPError as e:
        hint = ""
        if e.code in (401, 403):
            hint = ("\n\nRoblox didn't accept the API key. On create.roblox.com/dashboard/credentials check that the key:\n"
                    "  - has the \"Assets\" API system with Read and Write,\n"
                    "  - lists 0.0.0.0/0 (or your IP) under Accepted IP Addresses,\n"
                    "  - belongs to the same account as the user id you entered, and hasn't expired.\n"
                    "A new or changed key can take a minute or two to start working.")
        raise SystemExit(f"{method} {url} failed: {e.code} {e.read().decode(errors='replace')}{hint}")


def upload(path, key, creator, asset_type, content_type):
    boundary = uuid.uuid4().hex
    meta = {"assetType": asset_type, "displayName": f"PeakFlip {path.stem}", "description": "Peak Flip game asset",
            "creationContext": {"creator": creator}}
    body = (f"--{boundary}\r\nContent-Disposition: form-data; name=\"request\"\r\n\r\n{json.dumps(meta)}\r\n"
            f"--{boundary}\r\nContent-Disposition: form-data; name=\"fileContent\"; filename=\"{path.name}\"\r\n"
            f"Content-Type: {content_type}\r\n\r\n").encode() + path.read_bytes() + f"\r\n--{boundary}--\r\n".encode()
    op = request("POST", f"{API}/assets", key, body, {"Content-Type": f"multipart/form-data; boundary={boundary}"})
    op_id = op.get("operationId") or op.get("path", "").split("/")[-1]
    for _ in range(60):
        if op.get("done"):
            return op["response"]["assetId"]
        time.sleep(1.5)
        op = request("GET", f"{API}/operations/{op_id}", key)
    raise SystemExit(f"Timed out waiting for {path.name}")


def main():
    key = os.environ.get("ROBLOX_API_KEY")
    user, group = os.environ.get("ROBLOX_USER_ID"), os.environ.get("ROBLOX_GROUP_ID")
    # take the key from the clipboard rather than the command line, so it doesn't end up in the shell's history
    def clipboard():
        try:
            return subprocess.run(["pbpaste"], capture_output=True, text=True, timeout=5).stdout.strip()
        except (OSError, subprocess.SubprocessError):
            return ""

    def looks_like_key(text):
        return len(text) >= 40 and not any(c.isspace() for c in text)

    while not key:
        input("Copy your API key on create.roblox.com/dashboard/credentials (Cmd+C), then press Enter here... ")
        text = clipboard()
        if looks_like_key(text):
            key = text
            print(f"Got the API key from your clipboard ({len(key)} characters).")
        else:
            print("That doesn't look like an API key. Copy the key itself and try again (Ctrl+C here to quit).")
    if not (user or group):
        user = input("Your Roblox user id (the number in your profile URL): ").strip()
    if not key or not (user or group) or not (user or group).isdigit():
        raise SystemExit(__doc__)
    creator = {"groupId": group} if group else {"userId": user}
    for folder, ext, asset_type, content_type, out, prefix in KINDS:
        ids = existing(out)
        todo = [p for p in sorted((ROOT / "assets" / folder).glob(f"*.{ext}")) if p.stem not in ids]
        print(f"{folder}: {len(ids)} already uploaded, {len(todo)} to go")
        for p in todo:
            ids[p.stem] = f"{prefix}{upload(p, key, creator, asset_type, content_type)}"
            print(f"  {p.stem}: {ids[p.stem]}")
            write(out, ids)  # save as we go, so a failure halfway loses nothing
    print("Done. Now rebuild the place:  cd roblox && rojo build -o PeakFlip.rbxlx")


if __name__ == "__main__":
    sys.exit(main())
