import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import * as THREE from '../lib/three.module.min.js';
const source = readFileSync(new URL('../game.js', import.meta.url), 'utf8');
const rand = (a, b) => (a + b) / 2;
test('particle buffers stay idle without live particles and colors upload only when emitted', () => {
  const world = new THREE.Group();
  const context = vm.createContext({ THREE, world, rand, LITE: false, LOW: false });
  vm.runInContext(source.slice(source.indexOf('const Particles = (() =>'), source.indexOf('// falling snow around the camera')) + '\nthis.particles = Particles;', context);
  const fx = context.particles, mesh = fx.obj, pos = mesh.geometry.attributes.position, col = mesh.geometry.attributes.color;
  fx.update(1 / 60);
  assert.equal(pos.version, 0); assert.equal(col.version, 0); assert.equal(mesh.visible, false);
  fx.emit(0, 1, 0, 400, 1, 1, 0xffffff);
  assert.equal(mesh.visible, true);
  const colors = col.version;
  fx.update(1 / 60);
  assert.ok(pos.version > 0); assert.equal(col.version, colors);
  fx.update(1);
  assert.equal(mesh.visible, false);
  const positions = pos.version;
  fx.update(1);
  assert.equal(pos.version, positions);
  fx.emit(0, 1, 0, 1, 1, 1, 0xff0000);
  assert.equal(mesh.visible, true);
});
test('clearing crash effects releases owned geometry and keeps cloned rider geometry alive', () => {
  const world = new THREE.Group();
  const context = vm.createContext({ THREE, world, rand, groundAt: () => [0] });
  vm.runInContext(source.slice(source.indexOf('const Debris = (() =>'), source.indexOf('\nconst fling =')) + '\nthis.debris = Debris;', context);
  const parent = new THREE.Group(), shared = new THREE.BoxGeometry(), part = new THREE.Mesh(shared);
  parent.add(part); world.add(parent);
  let sharedDisposals = 0; shared.addEventListener('dispose', () => sharedDisposals++);
  context.debris.throwParts([part], new THREE.Vector3(), new THREE.Vector3());
  context.debris.mark(0, 0, 1); context.debris.splat(0, 0);
  const marks = world.children.filter(obj => obj.geometry?.type === 'CircleGeometry');
  let ownedDisposals = 0;
  for (const obj of marks) obj.geometry.addEventListener('dispose', () => ownedDisposals++);
  context.debris.clear();
  assert.equal(marks.length, 13); assert.equal(ownedDisposals, 13); assert.equal(sharedDisposals, 0);
  assert.deepEqual(world.children, [parent]);
  context.debris.clear(); assert.equal(ownedDisposals, 13);
});
